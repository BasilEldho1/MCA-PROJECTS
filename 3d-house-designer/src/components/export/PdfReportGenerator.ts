import jsPDF from 'jspdf';
import { Project } from '../../types/floorplan';
import { formatArea } from '../../utils/unitConverter';

export const generatePdfReport = async (project: Project, viewMode?: string): Promise<void> => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const unit = project.unit;

  // Header Banner
  doc.setFillColor(15, 23, 42); // Deep Slate
  doc.rect(0, 0, pageWidth, 40, 'F');

  doc.setTextColor(56, 189, 248); // Cyan Accent
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('3D HOUSE FLOOR PLAN SPECIFICATION', 14, 18);

  doc.setTextColor(248, 250, 252);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Project: ${project.name}`, 14, 28);
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, pageWidth - 60, 28);

  // Metadata Box
  doc.setFillColor(241, 245, 249);
  doc.rect(14, 48, pageWidth - 28, 28, 'F');
  doc.setDrawColor(203, 213, 225);
  doc.rect(14, 48, pageWidth - 28, 28, 'S');

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('PROPERTY OVERVIEW', 18, 56);

  doc.setFont('helvetica', 'normal');
  doc.text(`House Type: ${project.houseType}`, 18, 64);
  doc.text(`Plot Width: ${project.plotWidth} ${unit}`, 18, 70);
  doc.text(`Plot Length: ${project.plotLength} ${unit}`, 80, 64);
  doc.text(`Floors: ${project.floorsCount} Level(s)`, 80, 70);

  const totalArea = project.rooms.reduce((acc, r) => acc + r.area, 0);
  doc.setFont('helvetica', 'bold');
  doc.text(`Total Interior Area: ${formatArea(totalArea, unit)}`, 140, 64);

  // Room Breakdown Table
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('ROOM SPECIFICATIONS & AREA BREAKDOWN', 14, 88);

  let yPos = 96;
  doc.setFillColor(30, 41, 59);
  doc.rect(14, yPos, pageWidth - 28, 8, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('ROOM NAME', 18, yPos + 5.5);
  doc.text('TYPE', 80, yPos + 5.5);
  doc.text('FLOOR MATERIAL', 125, yPos + 5.5);
  doc.text('AREA', 170, yPos + 5.5);

  yPos += 8;

  project.rooms.forEach((room, index) => {
    if (index % 2 === 0) {
      doc.setFillColor(255, 255, 255);
    } else {
      doc.setFillColor(241, 245, 249);
    }
    doc.rect(14, yPos, pageWidth - 28, 8, 'F');

    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'normal');
    doc.text(room.name, 18, yPos + 5.5);
    doc.text(room.type, 80, yPos + 5.5);
    doc.text(String(room.floorMaterial).toUpperCase(), 125, yPos + 5.5);
    doc.setFont('helvetica', 'bold');
    doc.text(formatArea(room.area, unit), 170, yPos + 5.5);

    yPos += 8;
  });

  // Capture Canvas Image
  const canvas = document.querySelector('canvas') as HTMLCanvasElement;
  if (canvas) {
    try {
      const imgData = canvas.toDataURL('image/png');
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(15, 23, 42);
      doc.text('FLOOR PLAN BLUEPRINT PREVIEW', 14, yPos + 14);

      doc.addImage(imgData, 'PNG', 14, yPos + 18, pageWidth - 28, 90);
    } catch (e) {
      console.warn('Canvas capture skipped');
    }
  }

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('Generated by cjworks | Architectural MCA Project Specification', 14, 285);

  doc.save(`${project.name.toLowerCase().replace(/\s+/g, '_')}_architectural_report.pdf`);
};
